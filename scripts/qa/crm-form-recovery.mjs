import fs from 'node:fs'
import path from 'node:path'
import assert from 'node:assert/strict'
import {webkit} from 'playwright'
const dir=path.resolve('.tmp/form-recovery-check')
const tag=process.argv[2]||'before'
const browser=await webkit.launch({headless:true})
const report={sourceHashes:JSON.parse(fs.readFileSync(path.join(dir,'source-hashes.json'))),checks:[],errors:[]}
try {
 const page=await browser.newPage({viewport:{width:900,height:900}})
 page.on('pageerror',e=>report.errors.push(String(e)))
 await page.route('**/*',route=>route.fulfill({contentType:'text/html',body:'<!doctype html><html><body><div id="root"></div></body></html>'}))
 await page.goto('http://127.0.0.1:3047/__isolated-form-check')
 await page.addScriptTag({content:fs.readFileSync(path.join(dir,'bundle.js'),'utf8')})
 await page.locator('[name=firstName]').fill('[INTERNAL TEST] Form recovery')
 await page.locator('[name=phone]').fill('6155550123')
 await page.locator('[name=message]').fill('Repair gate')
 await page.getByRole('button',{name:'More details',exact:true}).click()
 await page.locator('[name=service]').selectOption({label:'Aluminum / Boat Welding'})
 await page.locator('[name=referral]').selectOption({label:'Referral'})
 await page.getByRole('button',{name:'Save job',exact:true}).click()
 await page.waitForFunction(()=>window.submissions.length===1)
 report.checks.push({name:'intake-pending-locks',nameReadonly:await page.locator('[name=firstName]').evaluate(el=>el.readOnly),needReadonly:await page.locator('[name=message]').evaluate(el=>el.readOnly),serviceDisabled:await page.locator('[name=service]').isDisabled(),sourceDisabled:await page.getByRole('button',{name:'Walk-in',exact:true}).isDisabled(),dispositionDisabled:await page.getByRole('button',{name:'Not a job',exact:true}).isDisabled()})
 await page.getByRole('alert').waitFor()
 report.checks.push({name:'intake-error-retention',service:await page.locator('[name=service]').inputValue(),referral:await page.locator('[name=referral]').inputValue(),submission:await page.evaluate(()=>window.submissions.at(-1))})
 await page.getByRole('button',{name:'Close details',exact:true}).click()
 await page.getByRole('button',{name:'More details',exact:true}).click()
 report.checks.push({name:'intake-details-retention',service:await page.locator('[name=service]').inputValue(),referral:await page.locator('[name=referral]').inputValue()})
 if(tag!=='before') {
  const expected={service:'Aluminum / Boat Welding',referral:'Referral'}
  for(const check of report.checks.filter(item=>item.name.endsWith('retention'))) for(const [key,value] of Object.entries(expected))assert.equal(check[key],value,check.name+': '+key)
  for(const [key,value] of Object.entries(report.checks[0]))if(key!=='name')assert.equal(value,true,key)
  await page.getByRole('button',{name:'Walk-in',exact:true}).click()
  assert.equal(await page.locator('[name=service]').inputValue(),'')
  await page.getByRole('button',{name:'Phone call',exact:true}).click()
  assert.equal(await page.locator('[name=service]').inputValue(),expected.service)
  report.checks.push({name:'intake-source-isolation',passed:true})
  await page.getByRole('button',{name:'Close details',exact:true}).click()
  await page.getByRole('button',{name:'Save job',exact:true}).click()
  await page.waitForFunction(()=>window.submissions.length===2)
  await page.waitForFunction(()=>document.activeElement?.getAttribute('name')==='firstName'&&document.querySelector('form')?.getAttribute('aria-busy')==='false')
  const repeated=await page.evaluate(()=>window.submissions.at(-1))
  assert.equal(repeated.service,expected.service)
  assert.equal(repeated.referral,expected.referral)
  report.checks.push({name:'intake-closed-details-submit-and-repeat-error-focus',passed:true,submission:repeated})
  await page.evaluate(()=>window.actionMode='success')
  await page.getByRole('button',{name:'Save job',exact:true}).click()
  await page.getByRole('button',{name:'Undo',exact:true}).click()
  await page.locator('[name=firstName]').waitFor()
  await page.getByRole('button',{name:'More details',exact:true}).click()
  assert.equal(await page.locator('[name=service]').inputValue(),expected.service)
  assert.equal(await page.locator('[name=referral]').inputValue(),expected.referral)
  report.checks.push({name:'intake-success-undo-preserves-details',passed:true})
  await page.getByRole('button',{name:'Save job',exact:true}).click()
  await page.getByRole('button',{name:'Done',exact:true}).click()
  await page.locator('[name=firstName]').waitFor()
  assert.equal(await page.locator('[name=firstName]').inputValue(),'')
  assert.equal(await page.locator('[name=service]').inputValue(),'')
  assert.equal(await page.locator('[name=referral]').inputValue(),'')
  report.checks.push({name:'intake-success-new-job-clears-details',passed:true})
 }
 await page.evaluate(()=>window.mount('closeout'))
 await page.locator('.ops-done-bench textarea').first().fill('Finished the gate and adjusted on site. Two extra trips. Rework was required.')
 await page.getByRole('button',{name:'Review closeout',exact:true}).click()
 await page.locator('[name=fit]').selectOption('adjusted')
 await page.locator('[name=rework]').selectOption('yes')
 await page.locator('[name=extraTrips]').fill('2')
 await page.locator('[name=asBuiltDifferences]').fill('Adjusted hinge spacing')
 await page.getByRole('button',{name:'Complete job',exact:true}).click()
 await page.getByRole('button',{name:'Confirm completion',exact:true}).click()
 await page.waitForFunction(()=>document.querySelector('fieldset')?.disabled)
 report.checks.push({name:'closeout-pending-locks',sourceReadonly:await page.locator('.ops-done-bench textarea').first().evaluate(el=>el.readOnly),reviewDisabled:await page.getByRole('button',{name:'Review closeout',exact:true}).isDisabled(),fitDisabled:await page.locator('[name=fit]').isDisabled()})
 await page.getByRole('alert').waitFor()
 await page.waitForTimeout(100)
 report.checks.push({name:'closeout-error-retention',fit:await page.locator('[name=fit]').inputValue(),rework:await page.locator('[name=rework]').inputValue(),extraTrips:await page.locator('[name=extraTrips]').inputValue(),submission:await page.evaluate(()=>window.submissions.at(-1))})
 if(tag!=='before'){
  const last=report.checks.at(-1);assert.equal(last.fit,'adjusted');assert.equal(last.rework,'yes');assert.equal(last.extraTrips,'2');assert.equal(last.submission.fit,'adjusted');assert.equal(last.submission.rework,'yes')
  for(const [key,value]of Object.entries(report.checks.at(-2)))if(key!=='name')assert.equal(value,true,key)
  await page.locator('[name=completion]').selectOption('partial')
  await page.locator('[name=remainingWork]').fill('Adjust latch')
  const count=await page.evaluate(()=>window.submissions.length)
  await page.getByRole('button',{name:'File update · keep job open',exact:true}).click()
  await page.waitForFunction(()=>document.querySelector('fieldset')?.disabled)
  assert.equal(await page.locator('.ops-done-bench textarea').first().evaluate(el=>el.readOnly),true)
  await page.waitForFunction(()=>document.querySelector('fieldset')?.disabled===false)
  const partial=await page.evaluate(()=>window.submissions.at(-1))
  assert.equal(await page.evaluate(()=>window.submissions.length),count+1)
  assert.equal(partial.completion,'partial');assert.equal(partial.remainingWork,'Adjust latch')
  report.checks.push({name:'partial-closeout-pending-lock-and-draft-retention',passed:true})
  assert.deepEqual(report.errors,[])
 }
 console.log(JSON.stringify(report,null,2))
}finally{await browser.close();fs.writeFileSync(path.join(dir,tag+'.json'),JSON.stringify(report,null,2))}
